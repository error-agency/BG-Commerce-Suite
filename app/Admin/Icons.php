	/**
	 * Render an inline SVG icon.
	 *
	 * @param string $name  Icon name (see PATHS).
	 * @param int    $size  Pixel size.
	 * @param string $class Extra CSS class.
	 * @return string Safe SVG markup.
	 */
	public static function svg( $name, $size = 20, $class = '' ) {
		if ( ! isset( self::PATHS[ $name ] ) ) {
			return '';
		}

		return sprintf(
			'<svg class="bgcs-ico %1$s" width="%2$d" height="%2$d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">%3$s</svg>',
			esc_attr( $class ),
			(int) $size,
			self::PATHS[ $name ]
		);
	}

	/**
	 * Courier brand logo as an <img>, or '' when the courier has none.
	 *
	 * Core ships no courier assets — each add-on supplies its own logo URL:
	 *
	 *   add_filter( 'bgcs3_courier_logo_url', function ( $url, $id ) {
	 *       return 'speedy' === $id ? plugins_url( 'assets/img/speedy.svg', __FILE__ ) : $url;
	 *   }, 10, 2 );
	 *
	 * @param string $courier_id Courier id (e.g. 'speedy').
	 * @param string $alt        Alt text.
	 * @return string
	 */
	public static function courier_logo( $courier_id, $alt = '' ) {
		$courier_id = sanitize_key( $courier_id );
		if ( '' === $courier_id ) {
			return '';
		}

		/**
		 * Filter the courier's logo URL.
		 *
		 * @param string $url        Logo URL ('' = none).
		 * @param string $courier_id Courier id.
		 */
		$url = (string) apply_filters( 'bgcs3_courier_logo_url', '', $courier_id );

		if ( '' === $url ) {
			return '';
		}

		return '<img class="bgcs-courier-logo" src="' . esc_url( $url ) . '" alt="' . esc_attr( $alt ) . '" />';
	}
